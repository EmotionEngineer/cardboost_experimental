"""Exact C99 header export: a single self-contained scoring function.

The generated ``.h`` file has no dependencies besides ``<math.h>`` (``isnan``,
``expf``) and reproduces the card score within ``1e-7`` (verified by
``tests/test_sql_c99.py``).  Data tables are ``static const float`` arrays; the
routing mirrors engine ``bin_idx`` (right-open intervals, NaN shelf).
"""
from __future__ import annotations

from typing import List, Optional

from ._sem import CardIR

_HDR = """/* generated by cardboost 1.0.0 - Container v3.x scoring function
 * routing: right-open intervals [c_i, c_i+1) + NaN shelf (bin n+1) */
#ifndef CARDBOOST_MODEL_H
#define CARDBOOST_MODEL_H
#include <math.h>
"""

_FOOT = "#endif /* CARDBOOST_MODEL_H */\n"


def _arr(name: str, vals, ctype: str = "double") -> str:
    flat = list(vals)
    body = ", ".join(str(int(v)) if ctype == "int" else repr(float(v))
                     for v in flat)
    return f"static const {ctype} {name}[] = {{{body}}};\n"


def _bin_c(var: str, cuts_name: str, nc: int, out: str, indent: str) -> str:
    return (f"{indent}int {out} = 0;\n"
            f"{indent}if (isnan({var})) {out} = {nc + 1};\n"
            f"{indent}else {{ while ({out} < {nc} && {cuts_name}[{out}] <= {var}) {out}++; }}\n")


def to_c99(card, func_name: str = "cardboost_score",
           names: Optional[List[str]] = None) -> str:
    """Return a complete C99 header implementing the card."""
    from ._sem import card_to_ir
    ir = card if isinstance(card, CardIR) else card_to_ir(card, names=names)
    dim = ir.n_classes
    out: List[str] = [_HDR]
    decl: List[str] = []
    body: List[str] = []

    def cname(base: str, i: int) -> str:
        return f"{base}_{i}"

    # ---- mains tables ----------------------------------------------------
    for mi, m in enumerate(ir.mains):
        nc = len(m.cuts)
        if nc:
            decl.append(_arr(cname("cb_cuts", mi), m.cuts))
        if dim > 1:
            for c in range(dim):
                decl.append(_arr(cname("cb_V", f"{mi}_{c}"),
                                 [m.levels[i][c] for i in range(len(m.levels))]))
        else:
            decl.append(_arr(cname("cb_V", mi), m.levels))

    # ---- ray / grid / cell tables ---------------------------------------
    for ri, a in enumerate(ir.rays):
        decl.append(_arr(cname("cb_gj", ri), a.gj))
        decl.append(_arr(cname("cb_rgj", ri), a.rgj))
        decl.append(_arr(cname("cb_gk", ri), a.gk))
        decl.append(_arr(cname("cb_rgk", ri), a.rgk))
        if a.ucuts:
            decl.append(_arr(cname("cb_ucuts", ri), a.ucuts))
        if dim > 1:
            for c in range(dim):
                decl.append(_arr(cname("cb_rV", f"{ri}_{c}"),
                                 [a.levels[i][c] for i in range(len(a.levels))]))
        else:
            decl.append(_arr(cname("cb_rV", ri), a.levels))

    for gi, g in enumerate(ir.grids):
        A, B = len(g.cj) + 2, len(g.ck) + 2
        if g.cj:
            decl.append(_arr(cname("cb_gcj", gi), g.cj))
        if g.ck:
            decl.append(_arr(cname("cb_gck", gi), g.ck))
        for c in range(dim):
            flat = []
            for a_ in range(A):
                for b_ in range(B):
                    flat.append(g.table[a_][b_][c] if dim > 1 else g.table[a_][b_])
            decl.append(_arr(cname("cb_gT", f"{gi}_{c}" if dim > 1 else gi), flat))

    for ci, cell in enumerate(ir.cells):
        A, B = len(cell.cj) + 2, len(cell.ck) + 2
        if cell.cj:
            decl.append(_arr(cname("cb_ccj", ci), cell.cj))
        if cell.ck:
            decl.append(_arr(cname("cb_cck", ci), cell.ck))
        for c in range(dim):
            flat = []
            for a_ in range(A):
                for b_ in range(B):
                    flat.append(cell.table[a_][b_][c] if dim > 1 else cell.table[a_][b_])
            decl.append(_arr(cname("cb_cT", f"{ci}_{c}" if dim > 1 else ci), flat))

    for qi, q in enumerate(ir.qmiss):
        js = [j for j, _ in q.shelves]
        ws = [w for _, w in q.shelves]
        decl.append(_arr(cname("cb_qj", qi), js, ctype="int"))
        decl.append(_arr(cname("cb_qw", qi), ws))
        if q.qcuts:
            decl.append(_arr(cname("cb_qcuts", qi), q.qcuts))
        if dim > 1:
            for c in range(dim):
                decl.append(_arr(cname("cb_qV", f"{qi}_{c}"),
                                 [q.levels[i][c] for i in range(len(q.levels))]))
        else:
            decl.append(_arr(cname("cb_qV", qi), q.levels))

    # ---- function signature ---------------------------------------------
    if dim > 1:
        sig = f"static void {func_name}(const double *x, double *eta)"
    else:
        sig = f"static double {func_name}(const double *x)"
    body.append(sig + " {\n")
    nfeat = max([m.j for m in ir.mains] + [a.j for a in ir.rays]
                + [g.j for g in ir.grids] + [c.j for c in ir.cells] + [0]) + 1
    for j in range(nfeat):
        body.append(f"    double x{j} = x[{j}];\n")
    if dim > 1:
        for c in range(dim):
            b0c = ir.b0[c]
            body.append(f"    double s{c} = {repr(float(b0c))};\n")
    else:
        body.append(f"    double s = {repr(float(ir.b0))};\n")

    # ---- mains -----------------------------------------------------------
    for mi, m in enumerate(ir.mains):
        nc = len(m.cuts)
        body.append(_bin_c(f"x{m.j}", cname("cb_cuts", mi), nc, f"b{mi}", "    "))
        for c in range(dim):
            tgt = f"s{c}" if dim > 1 else "s"
            body.append(f"    {tgt} += (double){cname('cb_V', f'{mi}_{c}' if dim > 1 else mi)}[b{mi}];\n")

    # ---- rays ------------------------------------------------------------
    for ri, a in enumerate(ir.rays):
        ngj, ngk = len(a.gj), len(a.gk)
        body.append(
            f"    double rj{ri} = (x{a.j} <= {repr(a.gj[0])}) ? {repr(a.rgj[0])} :\n"
            f"        (x{a.j} >= {repr(a.gj[-1])}) ? {repr(a.rgj[-1])} : 0.0;\n")
        body.append(f"    if (rj{ri} == 0.0) {{\n")
        for s in range(ngj - 1):
            slope = (a.rgj[s + 1] - a.rgj[s]) / (a.gj[s + 1] - a.gj[s]) if a.gj[s + 1] != a.gj[s] else 0.0
            body.append(f"        if (x{a.j} < {repr(a.gj[s + 1])}) "
                        f"rj{ri} = {repr(a.rgj[s])} + (x{a.j} - {repr(a.gj[s])}) * {repr(slope)};\n        else ")
        body.append(f"rj{ri} = {repr(a.rgj[-1])};\n    }}\n")
        body.append(
            f"    double rk{ri} = (x{a.k} <= {repr(a.gk[0])}) ? {repr(a.rgk[0])} :\n"
            f"        (x{a.k} >= {repr(a.gk[-1])}) ? {repr(a.rgk[-1])} : 0.0;\n")
        body.append(f"    if (rk{ri} == 0.0) {{\n")
        for s in range(ngk - 1):
            slope = (a.rgk[s + 1] - a.rgk[s]) / (a.gk[s + 1] - a.gk[s]) if a.gk[s + 1] != a.gk[s] else 0.0
            body.append(f"        if (x{a.k} < {repr(a.gk[s + 1])}) "
                        f"rk{ri} = {repr(a.rgk[s])} + (x{a.k} - {repr(a.gk[s])}) * {repr(slope)};\n        else ")
        body.append(f"rk{ri} = {repr(a.rgk[-1])};\n    }}\n")
        body.append(f"    double u{ri} = {repr(a.a)} * rj{ri} + {repr(a.b)} * rk{ri};\n")
        ncu = len(a.ucuts)
        body.append(_bin_c(f"u{ri}", cname("cb_ucuts", ri), ncu, f"ub{ri}", "    "))
        body.append(f"    int ins{ri} = (x{a.j} >= {repr(a.xmin_j)} && x{a.j} <= {repr(a.xmax_j)} &&\n"
                    f"                   x{a.k} >= {repr(a.xmin_k)} && x{a.k} <= {repr(a.xmax_k)});\n")
        for c in range(dim):
            tgt = f"s{c}" if dim > 1 else "s"
            tab = cname("cb_rV", f"{ri}_{c}" if dim > 1 else ri)
            body.append(f"    if (ins{ri}) {tgt} += (double){tab}[ub{ri}];\n")

    # ---- grids -----------------------------------------------------------
    for gi, g in enumerate(ir.grids):
        A, B = len(g.cj) + 2, len(g.ck) + 2
        body.append(_bin_c(f"x{g.j}", cname("cb_gcj", gi), len(g.cj), f"ga{gi}", "    "))
        body.append(_bin_c(f"x{g.k}", cname("cb_gck", gi), len(g.ck), f"gb{gi}", "    "))
        body.append(f"    int gins{gi} = (x{g.j} >= {repr(g.xmin_j)} && x{g.j} <= {repr(g.xmax_j)} &&\n"
                    f"                    x{g.k} >= {repr(g.xmin_k)} && x{g.k} <= {repr(g.xmax_k)});\n")
        for c in range(dim):
            tgt = f"s{c}" if dim > 1 else "s"
            tab = cname("cb_gT", f"{gi}_{c}" if dim > 1 else gi)
            body.append(f"    if (gins{gi}) {tgt} += (double){tab}[ga{gi} * {B} + gb{gi}];\n")

    # ---- cells -----------------------------------------------------------
    for ci, cell in enumerate(ir.cells):
        A, B = len(cell.cj) + 2, len(cell.ck) + 2
        body.append(_bin_c(f"x{cell.j}", cname("cb_ccj", ci), len(cell.cj), f"ca{ci}", "    "))
        body.append(_bin_c(f"x{cell.k}", cname("cb_cck", ci), len(cell.ck), f"cb{ci}", "    "))
        for c in range(dim):
            tgt = f"s{c}" if dim > 1 else "s"
            tab = cname("cb_cT", f"{ci}_{c}" if dim > 1 else ci)
            body.append(f"    {tgt} += (double){tab}[ca{ci} * {B} + cb{ci}];\n")

    # ---- q_miss ----------------------------------------------------------
    for qi, q in enumerate(ir.qmiss):
        nq = len(q.shelves)
        body.append(f"    double q{qi} = 0.0;\n")
        for si, (j, w) in enumerate(q.shelves):
            body.append(f"    if (isnan(x{j})) q{qi} += {repr(w)};\n")
        body.append(_bin_c(f"q{qi}", cname("cb_qcuts", qi), len(q.qcuts), f"qb{qi}", "    "))
        for c in range(dim):
            tgt = f"s{c}" if dim > 1 else "s"
            tab = cname("cb_qV", f"{qi}_{c}" if dim > 1 else qi)
            body.append(f"    {tgt} += (double){tab}[qb{qi}];\n")

    # ---- output / isolink ------------------------------------------------
    if dim > 1:
        body.append(f"    for (int c = 0; c < {dim}; c++) eta[c] = 0.0;\n")
        for c in range(dim):
            body.append(f"    eta[{c}] = s{c};\n")
    else:
        if ir.iso is not None:
            kx, kv = ir.iso.kx, ir.iso.kv
            body.append(f"    double g = s;\n")
            body.append(f"    double yv = {repr(kv[0])};\n")
            for si in range(len(kx) - 1):
                slope = (kv[si + 1] - kv[si]) / (kx[si + 1] - kx[si]) if kx[si + 1] != kx[si] else 0.0
                body.append(f"    if (s >= {repr(kx[si])}) "
                            f"yv = {repr(kv[si])} + (s - {repr(kx[si])}) * {repr(slope)};\n")
            body.append(f"    if (s > {repr(kx[-1])}) yv = {repr(kv[-1])};\n")
            body.append(f"    if (s < {repr(kx[0])}) yv = {repr(kv[0])};\n")
            body.append("    return yv;\n")
        else:
            body.append("    return s;\n")
    body.append("}\n")

    out.extend(decl)
    out.extend(body)
    out.append(_FOOT)
    return "".join(out)
